import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

import '../firebase_options.dart';

/// Compile-time Firebase overrides.
///
/// The generated `lib/firebase_options.dart` file is used by default. These
/// values only take precedence when you pass them with `--dart-define`, which
/// is handy for CI or for keeping keys out of the repository:
///
/// ```
/// flutter run \
///   --dart-define=FIREBASE_API_KEY=... \
///   --dart-define=FIREBASE_APP_ID=... \
///   --dart-define=FIREBASE_MESSAGING_SENDER_ID=... \
///   --dart-define=FIREBASE_PROJECT_ID=...
/// ```
class FirebaseConfig {
  const FirebaseConfig._();

  static const apiKey = String.fromEnvironment('FIREBASE_API_KEY');
  static const appId = String.fromEnvironment('FIREBASE_APP_ID');
  static const messagingSenderId = String.fromEnvironment(
    'FIREBASE_MESSAGING_SENDER_ID',
  );
  static const projectId = String.fromEnvironment('FIREBASE_PROJECT_ID');
  static const authDomain = String.fromEnvironment('FIREBASE_AUTH_DOMAIN');
  static const storageBucket = String.fromEnvironment(
    'FIREBASE_STORAGE_BUCKET',
  );

  /// True when enough values exist to build [options] by hand.
  static bool get isConfigured =>
      apiKey.isNotEmpty && appId.isNotEmpty && projectId.isNotEmpty;

  static FirebaseOptions get options => FirebaseOptions(
    apiKey: apiKey,
    appId: appId,
    messagingSenderId: messagingSenderId,
    projectId: projectId,
    authDomain: authDomain.isEmpty ? null : authDomain,
    storageBucket: storageBucket.isEmpty ? null : storageBucket,
  );
}

/// Initializes Firebase once, without ever breaking app start-up.
///
/// A missing `google-services.json` (or missing dart-defines) simply leaves
/// [isReady] false, and the auth screens keep their offline demo behaviour so
/// the UI can still be explored.
abstract final class FirebaseBootstrap {
  static bool _ready = false;
  static Object? _error;

  static bool get isReady => _ready;

  /// The initialization failure, if any. Handy while wiring a new project.
  static Object? get error => _error;

  static Future<void> initialize() async {
    if (_ready) return;

    try {
      if (Firebase.apps.isEmpty) {
        if (FirebaseConfig.isConfigured) {
          await Firebase.initializeApp(options: FirebaseConfig.options);
        } else {
          // Options generated by `flutterfire configure`.
          await Firebase.initializeApp(
            options: DefaultFirebaseOptions.currentPlatform,
          );
        }
      }
      _ready = Firebase.apps.isNotEmpty;
    } catch (error) {
      _ready = false;
      _error = error;
      if (kDebugMode) {
        debugPrint(
          'Firebase is not configured; continuing in offline demo mode. '
          'Run `flutterfire configure` or pass FIREBASE_* dart-defines. '
          'Reason: $error',
        );
      }
    }
  }
}
